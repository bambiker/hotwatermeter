#!/usr/bin/env python3
"""Regenerate the FAQPage structured data in faq.html from its own questions and answers.

Run after editing faq.html:  python3 tools/build_faq_ld.py
"""
import html
import json
import re
from pathlib import Path

PAGE = Path(__file__).resolve().parent.parent / 'faq.html'
MARK = '<!-- FAQ structured data: generated by tools/build_faq_ld.py -->'


def text(fragment):
    fragment = re.sub(r'<(br|/p|/li|/tr|/td|/th)\b[^>]*>', ' ', fragment)  # block ends become spaces
    fragment = re.sub(r'<[^>]+>', '', fragment)  # inline tags (b, span, a) vanish without adding space
    return re.sub(r'\s+', ' ', html.unescape(fragment)).strip()


def main():
    page = PAGE.read_text(encoding='utf-8')
    page = re.sub(re.escape(MARK) + r'\n<script type="application/ld\+json">.*?</script>\n', '', page, flags=re.S)
    page = re.sub(r'<!-- generated from the questions below[^\n]*\n<script type="application/ld\+json">.*?</script>\n', '', page, flags=re.S)
    qa = [{'@type': 'Question', 'name': text(q), 'acceptedAnswer': {'@type': 'Answer', 'text': text(a)}}
          for q, a in re.findall(r'<details[^>]*>\s*<summary>(.*?)</summary>\s*<div>(.*?)</div>\s*</details>', page, re.S)]
    data = json.dumps({'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': qa}, ensure_ascii=False, indent=1)
    page = page.replace('</head>', f'{MARK}\n<script type="application/ld+json">\n{data}\n</script>\n</head>', 1)
    PAGE.write_text(page, encoding='utf-8')
    print(f'{len(qa)} questions')


if __name__ == '__main__':
    main()
